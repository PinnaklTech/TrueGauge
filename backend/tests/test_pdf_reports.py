def test_inventory_1000_rows_smoke():
    rows = [
        _eq(id=i, tag=f"T-{i:04d}", name=f"Gauge {i}", status="calibrated", next_offset=30 + (i % 40))
        for i in range(1000)
    ]
    bundle = make_report(
        tenant_name="Acme",
        tenant_slug="acme",
        report_type="inventory",
        fmt="pdf",
        rows=rows,  # type: ignore[arg-type]
        timezone_name="UTC",
        extras=_extras(report_id="TG-RPT-20261021-1000"),
    )
    assert bundle.content.startswith(b"%PDF")
    assert bundle.row_count == 1000
    # Typical 50-row target is << 1MB; 1000 rows should still be modest
    assert len(bundle.content) < 2_000_000


