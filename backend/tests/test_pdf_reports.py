def pdf_plain_text(content: bytes) -> str:
    """Best-effort extract of Latin-1 text from compressed PDF streams."""
    parts = re.split(rb"stream\r?\n", content)
    chunks: list[str] = []
    for part in parts[1:]:
        data = part.split(rb"endstream")[0]
        if data.endswith(b"\r\n"):
            data = data[:-2]
        elif data.endswith(b"\n"):
            data = data[:-1]
        try:
            chunks.append(zlib.decompress(data).decode("latin-1", errors="ignore"))
        except Exception:
            continue
    return "\n".join(chunks)


