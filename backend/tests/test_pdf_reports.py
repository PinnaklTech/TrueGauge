    bundle = make_report(
        tenant_name="Acme Precision Components",
        tenant_slug="acme",
        report_type=report_type,  # type: ignore[arg-type]
        fmt="pdf",
        rows=SAMPLE_ROWS,  # type: ignore[arg-type]
        timezone_name="Asia/Kolkata",
        date_format="DD MMM YYYY",
        time_format="12h",
        extras=_extras(),
    )
    assert bundle.content.startswith(b"%PDF")
    assert bundle.report_id == "TG-RPT-20261021-0142"
    assert bundle.filename == "TG-RPT-20261021-0142.pdf"
    text = pdf_plain_text(bundle.content)
    assert "Thetruegage" in text
    assert "Report generated by Thetruegage" in text
    assert "Calibration Made Simple" in text
    assert "app.thetruegage.com" in text
    assert "TG-RPT-20261021-0142" in text
    assert "Page " in text
    assert "Confidential" in text
    assert "Acme Precision Components" in text


