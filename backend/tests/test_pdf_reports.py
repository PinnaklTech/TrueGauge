def test_filter_and_stats_use_provided_today():
    overdue = filter_equipment(SAMPLE_ROWS, "overdue", TODAY)  # type: ignore[arg-type]
    assert any(r.tag == "MIC-0042" for r in overdue)
    due = filter_equipment(SAMPLE_ROWS, "due", TODAY)  # type: ignore[arg-type]
    assert any(r.tag == "CAL-0211" for r in due)
    stats = compliance_stats(SAMPLE_ROWS, TODAY)  # type: ignore[arg-type]
    assert stats["total"] == 8
    assert stats["inactive"] == 1
    assert 0 <= stats["readiness"] <= 100


